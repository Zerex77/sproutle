# Builds build/relay/words.js for Relay: the four-letter words you're allowed to play, and the daily
# start -> goal pairs. Run: python3 build/relay/make_words.py
# Words come from words4.txt (SCOWL/ESDB sizes). Every daily pair is joined by a ladder of common words.
import json, os, random
from collections import deque

D = os.path.dirname(os.path.abspath(__file__))
# Words that would look bad on a public wall of chains
BLOCK = set("""anal anus arse bich boob cock coon cums cunt dago dick dike dong dyke fags fuck gimp gook homo hump
jism jizz kike knob muff nazi nigs paki piss poon porn puss quim rape scum shag shit slag slut smut spic spaz tits
turd twat wank wops yids yobs suck sexy sext poos poop pube shat fart fags crap damn hell butt boobs nude""".split())

words = {}
for line in open(os.path.join(D, "words4.txt")):
    if line.startswith("#") or not line.strip(): continue
    w, s = line.split(); words[w] = int(s)
# Everything up to size 50, plus the familiar words from the size-60 band (60 and up is mostly archaic or jargon,
# which would let the "best possible" count lean on words nobody knows)
FAMILIAR60 = set("""alps bios bonk boxy brie bros caff capo ciao coco cyan dang dibs ditz doge drat eave faux fave gaga
ghee glam goth gran hiya hots java jean joey kart lido luge lulu mage magi mags maxi mega meth mics midi mosh oohs oozy
orzo ouzo phew pics plat pong puce rads roux ruck shiv souk tech trad vibe vino whee yuan yurt zine""".split())
VALID = sorted(w for w in words if w not in BLOCK and (words[w] <= 50 or w in FAMILIAR60))
COMMON = set(w for w in VALID if words[w] <= 35)

def neighbors(w, pool):
    for i in range(4):
        for c in "abcdefghijklmnopqrstuvwxyz":
            if c != w[i]:
                n = w[:i] + c + w[i + 1:]
                if n in pool: yield n

def dist_from(src, pool):
    d = {src: 0}; q = deque([src])
    while q:
        w = q.popleft()
        for n in neighbors(w, pool):
            if n not in d: d[n] = d[w] + 1; q.append(n)
    return d

# Starts and goals are everyday words people know (size 35) that aren't plurals or -ed forms
nice = [w for w in COMMON if not w.endswith("s") and not w.endswith("ed")]
rng = random.Random(1013)
pairs, seen = [], set()
while len(pairs) < 730:
    a = rng.choice(nice)
    d = dist_from(a, COMMON)
    far = [w for w, k in d.items() if 5 <= k <= 7 and w in nice and w != a]
    if not far: continue
    b = rng.choice(far)
    if (a, b) in seen or (b, a) in seen: continue
    seen.add((a, b)); pairs.append([a, b, d[b]])

# A few classic ladders for the first weeks (No. 4 = Oct 16, 2026)
CURATED = [("word","game"),("cold","warm"),("head","tail"),("lead","gold"),("fish","bird"),("sock","shoe"),("hate","love"),
           ("ship","dock"),("rain","snow"),("milk","cake"),("seed","tree"),("work","play"),("lose","find"),("dark","glow")]
cur = []
for a, b in CURATED:
    d = dist_from(a, COMMON).get(b)
    if d and 4 <= d <= 8: cur.append([a, b, d])
    else: print("skipped", a, b, d)
pairs = pairs[:3] + cur + [p for p in pairs[3:] if (p[0], p[1]) not in CURATED]

out = ("// Generated by make_words.py. Words from SCOWL/ESDB (github.com/en-wl/wordlist).\n"
       "window.RELAY_WORDS=" + json.dumps(" ".join(VALID)) + ";\n"
       "window.RELAY_COMMON=" + json.dumps(" ".join(sorted(COMMON))) + ";\n"
       "window.RELAY_PAIRS=" + json.dumps(pairs, separators=(",", ":")) + ";\n")
open(os.path.join(D, "words.js"), "w").write(out)
from collections import Counter
print(len(VALID), "valid,", len(COMMON), "common,", len(pairs), "pairs, lengths", dict(Counter(p[2] for p in pairs)), f"{len(out)//1024} KB")
print(pairs[:12])
